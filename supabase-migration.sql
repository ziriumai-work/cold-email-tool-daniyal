-- Safe Supabase/Postgres migration for the cold email app
-- This script is idempotent and avoids problematic constraint re-creation.

CREATE TABLE IF NOT EXISTS companies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  website TEXT,
  contact_email TEXT,
  phone TEXT,
  all_emails TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT
);

CREATE TABLE IF NOT EXISTS drafts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  subject TEXT,
  body TEXT,
  research_summary TEXT,
  offer TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  error TEXT,
  sent_at TEXT,
  scheduled_at TEXT,
  scheduled_tz TEXT,
  message_id TEXT,
  sender_key TEXT,
  sender_name TEXT,
  sender_email TEXT,
  replied_at TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT,
  tracking_id TEXT,
  opened_at TEXT,
  open_count INTEGER DEFAULT 0,
  last_opened_at TEXT,
  clicked_at TEXT,
  click_count INTEGER DEFAULT 0,
  last_clicked_at TEXT
);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT
);

CREATE TABLE IF NOT EXISTS replies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id INTEGER REFERENCES drafts(id) ON DELETE SET NULL,
  company_id INTEGER REFERENCES companies(id) ON DELETE SET NULL,
  from_email TEXT,
  subject TEXT,
  snippet TEXT,
  imap_message_id TEXT UNIQUE,
  status TEXT DEFAULT 'new',
  notes TEXT,
  received_at TEXT,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::TEXT
);

DO $$
BEGIN
  -- If the tables already exist from a prior partial setup, add any missing columns safely.
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'scheduled_at'
  ) THEN
    ALTER TABLE drafts ADD COLUMN scheduled_at TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'scheduled_tz'
  ) THEN
    ALTER TABLE drafts ADD COLUMN scheduled_tz TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'companies' AND column_name = 'phone'
  ) THEN
    ALTER TABLE companies ADD COLUMN phone TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'companies' AND column_name = 'all_emails'
  ) THEN
    ALTER TABLE companies ADD COLUMN all_emails TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'message_id'
  ) THEN
    ALTER TABLE drafts ADD COLUMN message_id TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'sender_key'
  ) THEN
    ALTER TABLE drafts ADD COLUMN sender_key TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'sender_name'
  ) THEN
    ALTER TABLE drafts ADD COLUMN sender_name TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'sender_email'
  ) THEN
    ALTER TABLE drafts ADD COLUMN sender_email TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'replied_at'
  ) THEN
    ALTER TABLE drafts ADD COLUMN replied_at TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'tracking_id'
  ) THEN
    ALTER TABLE drafts ADD COLUMN tracking_id TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'opened_at'
  ) THEN
    ALTER TABLE drafts ADD COLUMN opened_at TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'open_count'
  ) THEN
    ALTER TABLE drafts ADD COLUMN open_count INTEGER DEFAULT 0;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'last_opened_at'
  ) THEN
    ALTER TABLE drafts ADD COLUMN last_opened_at TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'clicked_at'
  ) THEN
    ALTER TABLE drafts ADD COLUMN clicked_at TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'click_count'
  ) THEN
    ALTER TABLE drafts ADD COLUMN click_count INTEGER DEFAULT 0;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'drafts' AND column_name = 'last_clicked_at'
  ) THEN
    ALTER TABLE drafts ADD COLUMN last_clicked_at TEXT;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'replies' AND column_name = 'status'
  ) THEN
