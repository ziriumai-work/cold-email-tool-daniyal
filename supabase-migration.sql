  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'replies' AND column_name = 'notes'
  ) THEN
    ALTER TABLE replies ADD COLUMN notes TEXT;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_drafts_company_id ON drafts(company_id);
CREATE INDEX IF NOT EXISTS idx_drafts_status ON drafts(status);
CREATE INDEX IF NOT EXISTS idx_drafts_tracking_id ON drafts(tracking_id);
CREATE INDEX IF NOT EXISTS idx_replies_draft_id ON replies(draft_id);
CREATE INDEX IF NOT EXISTS idx_replies_company_id ON replies(company_id);

-- Atomic open tracking (no race condition)
CREATE OR REPLACE FUNCTION track_open(p_tracking_id TEXT, p_now TIMESTAMPTZ)
RETURNS void LANGUAGE sql AS $$
  UPDATE drafts
  SET
    open_count     = COALESCE(open_count, 0) + 1,
    opened_at      = COALESCE(opened_at, p_now),
    last_opened_at = p_now
  WHERE tracking_id = p_tracking_id;
$$;

-- Atomic click tracking (no race condition)
CREATE OR REPLACE FUNCTION track_click(p_tracking_id TEXT, p_now TIMESTAMPTZ)
RETURNS void LANGUAGE sql AS $$
  UPDATE drafts
  SET
    click_count     = COALESCE(click_count, 0) + 1,
    clicked_at      = COALESCE(clicked_at, p_now),
    last_clicked_at = p_now
  WHERE tracking_id = p_tracking_id;
$$;

-- Grant execute to anon role so the JS client can call them
GRANT EXECUTE ON FUNCTION track_open(TEXT, TIMESTAMPTZ) TO anon;
GRANT EXECUTE ON FUNCTION track_click(TEXT, TIMESTAMPTZ) TO anon;
